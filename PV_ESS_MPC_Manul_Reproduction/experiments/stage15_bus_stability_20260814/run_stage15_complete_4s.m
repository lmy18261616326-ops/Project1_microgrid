experimentDirectory = fileparts(mfilename('fullpath'));
modelFile = fullfile(experimentDirectory, 'manul_model_stage15_complete.slx');
[~, modelName] = fileparts(modelFile);
load_system(modelFile);

toWorkspaceBlocks = find_system(modelName, ...
    'LookUnderMasks', 'all', ...
    'FollowLinks', 'on', ...
    'BlockType', 'ToWorkspace');
originalDecimation = cell(size(toWorkspaceBlocks));
for blockIndex = 1:numel(toWorkspaceBlocks)
    originalDecimation{blockIndex} = ...
        get_param(toWorkspaceBlocks{blockIndex}, 'Decimation');
    set_param(toWorkspaceBlocks{blockIndex}, 'Decimation', '160');
end

simulationInput = Simulink.SimulationInput(modelName);
simulationInput = simulationInput.setModelParameter( ...
    'StartTime', '0', ...
    'StopTime', '4.0', ...
    'SignalLogging', 'off', ...
    'SaveOutput', 'off', ...
    'SaveState', 'off');

simulationTimer = tic;
simulationOutput = sim(simulationInput);
simulationElapsedSeconds = toc(simulationTimer);

for blockIndex = 1:numel(toWorkspaceBlocks)
    set_param(toWorkspaceBlocks{blockIndex}, 'Decimation', ...
        originalDecimation{blockIndex});
end

signalNames = { ...
    'V_dc', 'Vabc_grid', 'Vabc_load', ...
    'P_pv', 'P_bat', 'P_DC', 'P_DC_load1', 'P_DC_load2', 'Pf_threephase', ...
    'P_grid_threephase', 'P_ref_cmd', ...
    'Qf_threephase', 'Q_grid_threephase', 'Q_ref_cmd', ...
    'I_ref_protected', 'I_bat_mean', 'Dpv', ...
    'offMPPT_final', 'SOC_internal', ...
    'Jmin_mpvc', 'Jmin_MPPC', ...
    'I_dis_limit_dyn', 'I_chg_limit_dyn', ...
    'bat_limit_active', 'bat_power_limit_active', ...
    'Vbat_safe_limit', 'I_PI_track', ...
    'P_ref_raw', 'Q_ref_raw', 'S_grid_current_max', ...
    'grid_current_limit_active', 'grid_Iabc', ...
    'Pdc1_cpl_command', 'Pdc2_cpl_command', ...
    'Rdc1_cpl_command', 'Rdc2_cpl_command'};

results = struct();
results.modelFile = modelFile;
results.createdAt = char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));
results.simulationElapsedSeconds = simulationElapsedSeconds;
results.stage15FixId = stage15_fix_id;
for signalIndex = 1:numel(signalNames)
    results.signals.(signalNames{signalIndex}) = ...
        simulationOutput.get(signalNames{signalIndex});
end

vdc = results.signals.V_dc;
vdcTime = vdc.Time(:);
vdcData = vdc.Data(:);
assert(all(isfinite(vdcData)), 'Vdc contains NaN or Inf.');

eventLabels = { ...
    'pre_ac_step'; ...
    'post_ac_step'; ...
    'post_dc_0p6MW'; ...
    'post_grid_connect'; ...
    'high_irradiance_grid_tied'; ...
    'post_dc_1MW_on'; ...
    'post_dc_1MW_off'; ...
    'post_grid_voltage_dip'};
eventWindows = [ ...
    0.30 0.45; ...
    0.70 0.90; ...
    1.12 1.20; ...
    1.70 1.75; ...
    2.20 2.40; ...
    2.58 2.70; ...
    3.10 3.20; ...
    3.75 3.90];

meanVdc = zeros(size(eventLabels));
stdVdc = zeros(size(eventLabels));
minVdc = zeros(size(eventLabels));
maxVdc = zeros(size(eventLabels));
for eventIndex = 1:numel(eventLabels)
    eventMask = vdcTime >= eventWindows(eventIndex, 1) & ...
        vdcTime < eventWindows(eventIndex, 2);
    meanVdc(eventIndex) = mean(vdcData(eventMask));
    stdVdc(eventIndex) = std(vdcData(eventMask));
    minVdc(eventIndex) = min(vdcData(eventMask));
    maxVdc(eventIndex) = max(vdcData(eventMask));
end

eventMetrics = table(eventLabels, eventWindows(:, 1), eventWindows(:, 2), ...
    meanVdc, stdVdc, minVdc, maxVdc, ...
    'VariableNames', {'Event', 'WindowStart_s', 'WindowEnd_s', ...
    'MeanVdc_V', 'StdVdc_V', 'MinVdc_V', 'MaxVdc_V'});
results.eventMetrics = eventMetrics;

gridVoltage = results.signals.Vabc_grid;
gridPreMask = gridVoltage.Time >= 3.35 & gridVoltage.Time < 3.45;
gridPostMask = gridVoltage.Time >= 3.75 & gridVoltage.Time < 3.90;
gridRmsPre = sqrt(mean(gridVoltage.Data(gridPreMask, :).^2, 1));
gridRmsPost = sqrt(mean(gridVoltage.Data(gridPostMask, :).^2, 1));
gridDipRatio = mean(gridRmsPost ./ gridRmsPre);

qReference = results.signals.Q_ref_cmd;
qActual = results.signals.Qf_threephase;
qLateMask = qReference.Time >= 3.75 & qReference.Time < 3.90;
qActualLateMask = qActual.Time >= 3.75 & qActual.Time < 3.90;

pdc1=results.signals.P_DC_load1;
pdc2=results.signals.P_DC_load2;
pdc1Command=results.signals.Pdc1_cpl_command;
pdc2Command=results.signals.Pdc2_cpl_command;
pdc1Mask=pdc1.Time>=1.12 & pdc1.Time<1.20;
pdc2Mask=pdc2.Time>=2.58 & pdc2.Time<2.70;
pdc1CommandMask=pdc1Command.Time>=1.12 & pdc1Command.Time<1.20;
pdc2CommandMask=pdc2Command.Time>=2.58 & pdc2Command.Time<2.70;
pdc1Mean=mean(pdc1.Data(pdc1Mask));
pdc2Mean=mean(pdc2.Data(pdc2Mask));
pdc1CommandMean=mean(pdc1Command.Data(pdc1CommandMask));
pdc2CommandMean=mean(pdc2Command.Data(pdc2CommandMask));

results.summary = struct( ...
    'vdcGlobalMin_V', min(vdcData), ...
    'vdcGlobalMax_V', max(vdcData), ...
    'vdcFinal_V', vdcData(end), ...
    'gridRmsPre_V', gridRmsPre, ...
    'gridRmsPost_V', gridRmsPost, ...
    'gridDipRatio', gridDipRatio, ...
    'qReferenceLate_var', mean(qReference.Data(qLateMask)), ...
    'qActualLate_var', mean(qActual.Data(qActualLateMask)), ...
    'batteryPowerMinimum_W', min(reshape(results.signals.P_bat.Data,[],1)), ...
    'batteryPowerMaximum_W', max(reshape(results.signals.P_bat.Data,[],1)), ...
    'batLimitDuration_s', trapz(results.signals.bat_limit_active.Time, ...
        double(results.signals.bat_limit_active.Data(:)>0.5)), ...
    'gridLimitDuration_s', trapz(results.signals.grid_current_limit_active.Time, ...
        double(results.signals.grid_current_limit_active.Data(:)>0.5)), ...
    'dc1CplCommandMean_W', pdc1CommandMean, ...
    'dc1CplActualMean_W', pdc1Mean, ...
    'dc1CplTrackingError_percent',100*(pdc1Mean-pdc1CommandMean)/pdc1CommandMean, ...
    'dc2CplCommandMean_W', pdc2CommandMean, ...
    'dc2CplActualMean_W', pdc2Mean, ...
    'dc2CplTrackingError_percent',100*(pdc2Mean-pdc2CommandMean)/pdc2CommandMean, ...
    'allFinite', all(isfinite(vdcData)));

resultsFile = fullfile(experimentDirectory, ...
    'stage15_complete_results.mat');
save(resultsFile, 'results', '-v7.3');
writetable(eventMetrics, fullfile(experimentDirectory, ...
    'stage15_event_metrics.csv'));

summaryFile = fullfile(experimentDirectory, 'stage15_summary.json');
summaryHandle = fopen(summaryFile, 'w');
assert(summaryHandle ~= -1, 'Unable to create summary JSON file.');
fprintf(summaryHandle, '%s', jsonencode(results.summary, 'PrettyPrint', true));
fclose(summaryHandle);

set(groot, 'defaultFigureVisible', 'off');
eventTimes = [0.5 1.0 1.4 1.6 2.5 3.0 3.5];

overviewFigure = figure('Color', 'w', 'Position', [50 50 1400 900]);
overviewLayout = tiledlayout(3, 1, 'TileSpacing', 'compact', ...
    'Padding', 'compact');

nexttile(overviewLayout);
plot(vdc.Time, vdc.Data, 'LineWidth', 1.0);
yline(1200, '--k', '1200 V');
for eventTime = eventTimes
    xline(eventTime, ':', 'Color', [0.5 0.5 0.5]);
end
grid on;
ylabel('V_{dc} (V)');
title('Stage 15 complete scenario: DC-link voltage');

nexttile(overviewLayout);
powerSignals = {'P_pv', 'P_bat', 'P_DC', ...
    'Pf_threephase', 'P_grid_threephase'};
powerLabels = {'PV', 'Battery (+discharge)', 'DC load', ...
    'Interlink AC', 'Grid (+export)'};
hold on;
for signalIndex = 1:numel(powerSignals)
    powerSignal = results.signals.(powerSignals{signalIndex});
    powerData = reshape(powerSignal.Data, [], 1);
    plot(powerSignal.Time, powerData/1e6, 'LineWidth', 0.9);
end
hold off;
for eventTime = eventTimes
    xline(eventTime, ':', 'Color', [0.75 0.75 0.75]);
end
grid on;
ylabel('Power (MW)');
legend(powerLabels, 'Location', 'eastoutside');
title('Active-power balance');

nexttile(overviewLayout);
plot(results.signals.Q_ref_cmd.Time, ...
    reshape(results.signals.Q_ref_cmd.Data, [], 1)/1e6, 'LineWidth', 1.0);
hold on;
plot(results.signals.Qf_threephase.Time, ...
    reshape(results.signals.Qf_threephase.Data, [], 1)/1e6, 'LineWidth', 0.9);
plot(results.signals.Q_grid_threephase.Time, ...
    reshape(results.signals.Q_grid_threephase.Data, [], 1)/1e6, 'LineWidth', 0.9);
hold off;
for eventTime = eventTimes
    xline(eventTime, ':', 'Color', [0.75 0.75 0.75]);
end
grid on;
xlabel('Time (s)');
ylabel('Reactive power (Mvar)');
legend({'Q reference', 'Interlink Q', 'Grid Q'}, ...
    'Location', 'eastoutside');
title('Q-V droop response');

exportgraphics(overviewFigure, fullfile(experimentDirectory, ...
    'stage15_complete_overview.png'), 'Resolution', 180);
close(overviewFigure);

gridTimeStep = median(diff(gridVoltage.Time));
samplesPerCycle = max(2, round((1/f_grid)/gridTimeStep));
gridMovingRms = sqrt(movmean(gridVoltage.Data.^2, ...
    samplesPerCycle, 1));
gridRmsAverage = mean(gridMovingRms, 2);
gridNominalRms = mean(gridRmsAverage(gridPreMask));

dipFigure = figure('Color', 'w', 'Position', [50 50 1200 700]);
dipLayout = tiledlayout(2, 1, 'TileSpacing', 'compact', ...
    'Padding', 'compact');
nexttile(dipLayout);
plot(gridVoltage.Time, gridRmsAverage/gridNominalRms, 'LineWidth', 1.1);
xline(3.5, ':r', 'Voltage dip');
yline(0.9, '--k', '0.9 pu');
xlim([3.3 4.0]);
ylim([0.82 1.05]);
grid on;
ylabel('Grid voltage (pu RMS)');
title('Physical 10% grid-voltage dip');

nexttile(dipLayout);
plot(vdc.Time, vdc.Data, 'LineWidth', 1.0);
xline(3.5, ':r', 'Voltage dip');
yline(1200, '--k');
xlim([3.3 4.0]);
grid on;
xlabel('Time (s)');
ylabel('V_{dc} (V)');
title('DC-link ride-through');

exportgraphics(dipFigure, fullfile(experimentDirectory, ...
    'stage15_grid_dip_zoom.png'), 'Resolution', 180);
close(dipFigure);

try
    sdiRunId = Simulink.sdi.createRun( ...
        'stage15_complete_actual_grid_dip_4s', 'vars', ...
        results.signals.V_dc, ...
        results.signals.P_pv, ...
        results.signals.P_bat, ...
        results.signals.P_DC, ...
        results.signals.Pf_threephase, ...
        results.signals.P_grid_threephase, ...
        results.signals.Q_ref_cmd, ...
        results.signals.Qf_threephase);
    sdiRun = Simulink.sdi.getRun(sdiRunId);
    sdiSignalCount = sdiRun.SignalCount;
catch sdiException
    warning('Stage15:SDIExport', ...
        'SDI run creation failed: %s', sdiException.message);
    sdiRunId = -1;
    sdiSignalCount = 0;
end

fprintf('STAGE15_COMPLETE_SIM_OK elapsed=%.1f s\n', ...
    simulationElapsedSeconds);
fprintf('VDC_GLOBAL min=%.3f max=%.3f final=%.3f\n', ...
    min(vdcData), max(vdcData), vdcData(end));
fprintf('GRID_RMS_PRE=[%.3f %.3f %.3f]\n', gridRmsPre);
fprintf('GRID_RMS_POST=[%.3f %.3f %.3f]\n', gridRmsPost);
fprintf('GRID_DIP_RATIO=%.6f\n', gridDipRatio);
fprintf('Q_LATE reference=%.3f actual=%.3f\n', ...
    results.summary.qReferenceLate_var, results.summary.qActualLate_var);
fprintf('SDI_RUN_ID=%d SIGNAL_COUNT=%d\n', sdiRunId, sdiSignalCount);
fprintf('RESULTS_FILE=%s\n', resultsFile);
disp(eventMetrics);

close_system(modelName, 0);
