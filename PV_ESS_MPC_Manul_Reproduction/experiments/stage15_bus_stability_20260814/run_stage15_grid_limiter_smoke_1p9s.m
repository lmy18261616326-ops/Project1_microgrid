%% Short grid-connect smoke test before the full 4 s run.
expDir=fileparts(mfilename('fullpath'));
mdl='manul_model_stage15_complete';
cd(expDir);
run(fullfile(expDir,'pvess_stage15_busfix_init.m'));
load_system(fullfile(expDir,[mdl '.slx']));

tw=find_system(mdl,'LookUnderMasks','all','FollowLinks','on','BlockType','ToWorkspace');
oldDec=cell(size(tw));
for k=1:numel(tw), oldDec{k}=get_param(tw{k},'Decimation'); set_param(tw{k},'Decimation','160'); end
in=Simulink.SimulationInput(mdl);
in=in.setModelParameter('StartTime','0','StopTime','1.9','SignalLogging','off', ...
    'SaveOutput','off','SaveState','off');
t=tic; out=sim(in); elapsed=toc(t);
for k=1:numel(tw), set_param(tw{k},'Decimation',oldDec{k}); end

vdc=out.get('V_dc'); prefRaw=out.get('P_ref_raw'); pref=out.get('P_ref_cmd');
qRaw=out.get('Q_ref_raw'); q=out.get('Q_ref_cmd'); smax=out.get('S_grid_current_max');
flag=out.get('grid_current_limit_active');
mask=vdc.Time>=1.70 & vdc.Time<=1.85;
[commonTP,iaP,ibP]=intersect(prefRaw.Time(:),pref.Time(:));
pAlignedError=prefRaw.Data(iaP)-pref.Data(ibP);
[commonTQ,iaQ,ibQ]=intersect(qRaw.Time(:),q.Time(:));
qAlignedError=qRaw.Data(iaQ)-q.Data(ibQ);
summary=struct( ...
    'elapsed_s',elapsed, ...
    'vdcMin_V',min(vdc.Data(:)), ...
    'vdcMax_V',max(vdc.Data(:)), ...
    'vdcGridMean_V',mean(vdc.Data(mask)), ...
    'prefRawLate_W',mean(prefRaw.Data(prefRaw.Time>=1.7)), ...
    'prefLate_W',mean(pref.Data(pref.Time>=1.7)), ...
    'qRawLate_var',mean(qRaw.Data(qRaw.Time>=1.7)), ...
    'qLate_var',mean(q.Data(q.Time>=1.7)), ...
    'smaxLate_VA',mean(smax.Data(smax.Time>=1.7)), ...
    'prefRawFinal_W',prefRaw.Data(end), ...
    'prefFinal_W',pref.Data(end), ...
    'prefAlignedSamples',numel(commonTP), ...
    'prefMaxAlignedError_W',max(abs(pAlignedError(:))), ...
    'qAlignedSamples',numel(commonTQ), ...
    'qMaxAlignedError_var',max(abs(qAlignedError(:))), ...
    'flagMaximum',max(flag.Data(:)), ...
    'limitDuration_s',trapz(flag.Time,double(flag.Data(:)>0.5)), ...
    'allFinite',all(isfinite(vdc.Data(:))));
fid=fopen(fullfile(expDir,'stage15_grid_limiter_smoke_1p9s.json'),'w');
fprintf(fid,'%s',jsonencode(summary,'PrettyPrint',true)); fclose(fid);
disp(summary);
close_system(mdl,0);
