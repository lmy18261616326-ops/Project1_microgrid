libraryName = 'spsThreePhaseProgrammableVoltageSourceLib';
load_system(libraryName);
blocks = find_system(libraryName, ...
    'LookUnderMasks', 'all', ...
    'FollowLinks', 'on', ...
    'Type', 'Block');

fprintf('BLOCK_COUNT=%d\n', numel(blocks));
for index = 1:numel(blocks)
    fprintf('%s | BlockType=%s | MaskType=%s | ReferenceBlock=%s\n', ...
        blocks{index}, ...
        get_param(blocks{index}, 'BlockType'), ...
        get_param(blocks{index}, 'MaskType'), ...
        get_param(blocks{index}, 'ReferenceBlock'));
end
